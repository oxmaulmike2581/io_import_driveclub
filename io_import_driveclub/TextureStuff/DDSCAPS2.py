from enum import IntFlag

class DDSCAPS2(IntFlag):
    CUBEMAP           = 0x200    # Required for a cube map.
    CUBEMAP_POSITIVEX = 0x400    # Required when these surfaces are stored in a cube map.
    CUBEMAP_NEGATIVEX = 0x800
    CUBEMAP_POSITIVEY = 0x1000
    CUBEMAP_NEGATIVEY = 0x2000
    CUBEMAP_POSITIVEZ = 0x4000
    CUBEMAP_NEGATIVEZ = 0x8000
    VOLUME            = 0x200000 # Required for a volume texture.

    DDS_CUBEMAP_POSITIVEX = CUBEMAP | CUBEMAP_POSITIVEX
    DDS_CUBEMAP_NEGATIVEX = CUBEMAP | CUBEMAP_NEGATIVEX
    DDS_CUBEMAP_POSITIVEY = CUBEMAP | CUBEMAP_POSITIVEY
    DDS_CUBEMAP_NEGATIVEY = CUBEMAP | CUBEMAP_NEGATIVEY
    DDS_CUBEMAP_POSITIVEZ = CUBEMAP | CUBEMAP_POSITIVEZ
    DDS_CUBEMAP_NEGATIVEZ = CUBEMAP | CUBEMAP_NEGATIVEZ
    DDS_CUBEMAP_ALLFACES  = DDS_CUBEMAP_POSITIVEX | DDS_CUBEMAP_NEGATIVEX | \
                            DDS_CUBEMAP_POSITIVEY | DDS_CUBEMAP_NEGATIVEY | \
                            DDS_CUBEMAP_POSITIVEZ | DDS_CUBEMAP_NEGATIVEZ

